export function getProductName(p: Product, lang: Language): string {
  if (lang === 'ar') return p.name_ar || p.name_fr || p.name_en;
  if (lang === 'en') return p.name_en || p.name_fr || p.name_ar;
  return p.name_fr || p.name_en || p.name_ar;
}

export function getProductDesc(p: Product, lang: Language): string {
  if (lang === 'ar') return p.description_ar || p.description_fr || p.description_en;
  if (lang === 'en') return p.description_en || p.description_fr || p.description_ar;
  return p.description_fr || p.description_en || p.description_ar;
}

export function formatMoney(amount: number | undefined | null, currency = 'MAD'): string {
  const num = Number(amount || 0);
  return `${num.toLocaleString('fr-MA', { minimumFractionDigits: 2, maximumFractionDigits: 2 })} ${currency}`;
}
